#!/usr/bin/env python3
"""Generate dist/casa-cards.js, the single entry point of the Casa cards.

Each card is its own file in dist/ (casa-*.js). The loader imports them with a
content hash in the URL, so a browser only re-downloads the cards that changed.
Usage: python3 scripts/build-casa-cards.py [new-version]
Without a version the current one is kept.
"""
import hashlib
import pathlib
import re
import sys

DIST = pathlib.Path(__file__).resolve().parent.parent / "dist"
LOADER = DIST / "casa-cards.js"
# Loaded one after the other, in this order (each needs the previous ones).
ORDERED = ["casa-tablet-style.js", "casa-tablet-base.js", "casa-room-card.js", "casa-floor-card.js"]


def main() -> None:
    version = sys.argv[1] if len(sys.argv) > 1 else None
    if version is None:
        match = re.search(r"casa-cards v(\d+\.\d+\.\d+)", LOADER.read_text(encoding="utf-8")) if LOADER.exists() else None
        version = match.group(1) if match else "1.0.0"
    if not re.fullmatch(r"\d+\.\d+\.\d+", version):
        sys.exit(f"invalid version: {version}")

    files = sorted(p.name for p in DIST.glob("casa-*.js") if p.name != LOADER.name)
    missing = [name for name in ORDERED if name not in files]
    if missing:
        sys.exit(f"missing ordered files: {missing}")

    def ref(name: str) -> str:
        digest = hashlib.sha256((DIST / name).read_bytes()).hexdigest()[:10]
        return f"./{name}?h={digest}"

    ordered = ",\n  ".join(f'"{ref(n)}"' for n in ORDERED)
    rest = ",\n  ".join(f'"{ref(n)}"' for n in files if n not in ORDERED)
    LOADER.write_text(
        f"""/* casa-cards v{version} — entry point of the Casa dashboard cards (generated by scripts/build-casa-cards.py; do not edit).
   One file per card; the hash in each URL changes only when that card changes, so browsers keep the others cached. */
const ORDERED = [
  {ordered},
];
const REST = [
  {rest},
];
const load = (u) => import(new URL(u, import.meta.url).href).catch((e) => console.error("casa-cards: failed to load " + u, e));
(async () => {{ for (const u of ORDERED) await load(u); }})();
REST.forEach(load);
console.info("casa-cards v{version}: " + (ORDERED.length + REST.length) + " cards");
""",
        encoding="utf-8",
    )
    print(f"casa-cards v{version}: {len(files)} files")


if __name__ == "__main__":
    main()
